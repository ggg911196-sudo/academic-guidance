
import streamlit as st

st.set_page_config(
    page_title="سامانه هدایت هوشمند تحصیلی",
    page_icon="🎓",
    layout="centered"
)

PATHWAYS = {
    "علوم تجربی": {
        "interests": ["زیست‌شناسی و سلامت", "پژوهش علمی"],
        "activities": ["آزمایش و پژوهش", "حل مسئله"],
    },
    "ریاضی و فیزیک": {
        "interests": ["ریاضی و فیزیک", "فناوری و رایانه"],
        "activities": ["حل مسئله", "ساخت و طراحی"],
    },
    "علوم انسانی": {
        "interests": ["جامعه و انسان", "زبان و ادبیات"],
        "activities": ["مطالعه و تحلیل", "نوشتن و گفتگو"],
    },
    "فنی و مهارتی": {
        "interests": ["فناوری و رایانه", "هنر و طراحی"],
        "activities": ["ساخت و طراحی", "کار عملی"],
    },
    "هنر": {
        "interests": ["هنر و طراحی", "زبان و ادبیات"],
        "activities": ["ساخت و طراحی", "نوشتن و گفتگو"],
    },
}

INTERESTS = [
    "زیست‌شناسی و سلامت",
    "ریاضی و فیزیک",
    "فناوری و رایانه",
    "جامعه و انسان",
    "زبان و ادبیات",
    "هنر و طراحی",
    "پژوهش علمی",
]

ACTIVITIES = [
    "حل مسئله",
    "آزمایش و پژوهش",
    "مطالعه و تحلیل",
    "ساخت و طراحی",
    "کار عملی",
    "نوشتن و گفتگو",
]

st.title("🎓 سامانه هدایت هوشمند مسیر تحصیلی")
st.caption("نمونه پژوهشی برای بررسی و توضیح گزینه‌های تحصیلی")

page = st.sidebar.radio(
    "بخش موردنظر",
    [
        "صفحه اصلی",
        "آزمایش سامانه",
        "درباره پژوهش",
        "روش و محدودیت‌ها",
    ],
)

if page == "صفحه اصلی":
    st.header("به سامانه خوش آمدید")
    st.write(
        "این نمونه اولیه تلاش می‌کند با استفاده از "
        "علاقه‌های اعلام‌شده، ترجیح فعالیت‌ها و آمادگی "
        "خوداظهاری، چند مسیر تحصیلی را برای بررسی بیشتر پیشنهاد کند."
    )
    st.info(
        "نتایج، پیشنهادهای اولیه‌اند؛ نه آزمون استعداد، "
        "پیش‌بینی موفقیت یا جایگزین مشاور تحصیلی."
    )
    st.write("از منوی کناری، بخش «آزمایش سامانه» را انتخاب کنید.")

elif page == "آزمایش سامانه":
    st.header("پرسش‌نامه آزمایشی")

    st.write(
        "اطلاعات هویتی وارد نکنید. پاسخ‌ها برای آزمایش "
        "نمونه اولیه هستند."
    )

    interest = st.selectbox(
        "۱. کدام حوزه بیشتر به علاقه شما نزدیک است؟",
        ["انتخاب کنید"] + INTERESTS,
    )

    activity = st.selectbox(
        "۲. کدام نوع فعالیت را بیشتر ترجیح می‌دهید؟",
        ["انتخاب کنید"] + ACTIVITIES,
    )

    readiness = st.slider(
        "۳. آمادگی فعلی خود برای پیگیری این علاقه را "
        "چگونه ارزیابی می‌کنید؟",
        min_value=0,
        max_value=10,
        value=5,
    )

    if st.button("تحلیل پاسخ‌ها", type="primary"):
        if interest == "انتخاب کنید" or activity == "انتخاب کنید":
            st.warning("لطفاً به دو پرسش اول پاسخ دهید.")
        else:
            results = []

            for pathway, criteria in PATHWAYS.items():
                interest_match = (
                    1.0 if interest in criteria["interests"] else 0.0
                )
                activity_match = (
                    1.0 if activity in criteria["activities"] else 0.0
                )
                readiness_score = readiness / 10

                score = (
                    0.50 * interest_match
                    + 0.30 * activity_match
                    + 0.20 * readiness_score
                )

                results.append(
                    (
                        pathway,
                        score,
                        interest_match,
                        activity_match,
                    )
                )

            results.sort(key=lambda item: item[1], reverse=True)

            st.subheader("نتیجه اولیه")
            st.caption(
                "امتیازها خروجی یک قاعده آزمایشی هستند "
                "و احتمال موفقیت تحصیلی نیستند."
            )

            for pathway, score, im, am in results:
                st.write(f"**{pathway}**")
                st.progress(score)
                st.write(f"امتیاز آزمایشی: {score * 100:.0f} از ۱۰۰")

                reasons = []
                if im:
                    reasons.append("ارتباط با حوزه علاقه انتخاب‌شده")
                if am:
                    reasons.append("ارتباط با فعالیت ترجیحی")
                if readiness >= 7:
                    reasons.append("آمادگی خوداظهاری نسبتاً بالا")
                elif readiness <= 3:
                    reasons.append("آمادگی خوداظهاری پایین؛ نیازمند بررسی بیشتر")

                if reasons:
                    st.write("دلایل: " + "؛ ".join(reasons))
                else:
                    st.write(
                        "این گزینه با دو انتخاب اصلی شما تطابق مستقیم "
                        "ندارد و صرفاً برای مقایسه نمایش داده شده است."
                    )

                st.divider()

            if results[0][1] - results[1][1] < 0.10:
                st.warning(
                    "امتیاز دو گزینه اول به هم نزدیک است؛ "
                    "بهتر است هر دو گزینه را بررسی کنید."
                )

            st.info(
                "برای انتخاب واقعی رشته، درس‌های موردعلاقه، "
                "عملکرد تحصیلی، شرایط آموزشی و گفت‌وگو با مشاور "
                "نیز اهمیت دارند؛ این نسخه همه این عوامل را نمی‌سنجد."
            )

elif page == "درباره پژوهش":
    st.header("درباره پژوهش")
    st.subheader(
        "هدایت هوشمند مسیر تحصیلی دانش‌آموزان دوره متوسطه دوم با هوش مصنوعی"
    )
    st.write(
        "هدف پژوهش، طراحی و ارزیابی اولیه یک نمونه سامانه "
        "پشتیبان تصمیم‌گیری تحصیلی است که پیشنهادهای خود را "
        "به‌صورت قابل توضیح ارائه کند."
    )
    st.write(
        "در این نسخه، امتیازدهی مبتنی بر قواعد از پیش تعریف‌شده "
        "است؛ سامانه مدل یادگیری ماشین آموزش‌دیده ندارد."
    )

elif page == "روش و محدودیت‌ها":
    st.header("روش و محدودیت‌های پژوهش")

    st.subheader("روش اولیه")
    st.write(
        "یک نمونه اولیه مبتنی بر امتیازدهی چندمعیاره ساخته شده "
        "و رفتار آن باید با سناریوهای آزمایشی از پیش تعریف‌شده "
        "بررسی شود."
    )

    st.subheader("فرمول آزمایشی")
    st.latex(
        r"S_p = 0.50I_p + 0.30A_p + 0.20R_p"
    )
    st.write(
        "در این فرمول، I میزان تطابق علاقه، A میزان تطابق فعالیت "
        "و R آمادگی خوداظهاری نرمال‌شده است."
    )

    st.subheader("محدودیت‌ها")
    st.markdown(
        """
        - وزن‌ها و معیارها هنوز اعتبارسنجی علمی نشده‌اند.
        - دسته‌بندی‌ها ساده و آزمایشی‌اند.
        - امتیازها احتمال موفقیت یا سنجه معتبر استعداد نیستند.
        - داده واقعی دانش‌آموزان هنوز ارزیابی نشده است.
        - اعتبار آموزشی سامانه به پژوهش و ارزیابی مستقل نیاز دارد.
        """
    )

    st.warning(
        "این نمونه برای پژوهش و آزمایش اولیه است و نباید به‌تنهایی "
        "مبنای تصمیم قطعی درباره رشته تحصیلی قرار گیرد."
              )
  
